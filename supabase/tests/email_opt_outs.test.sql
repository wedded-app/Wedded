begin;
create extension if not exists pgtap with schema extensions;
select plan(13);
set local role anon;
select throws_ok($$ select * from public.email_opt_outs $$, '42501', null, 'Anon cannot read opt-outs');
select throws_ok($$ insert into public.email_opt_outs(email) values ('anon@example.com') $$, '42501', null, 'Anon cannot insert opt-outs');
select throws_ok($$ delete from public.email_opt_outs $$, '42501', null, 'Anon cannot delete opt-outs');
select throws_ok($$ update public.email_opt_outs set email = 'anon@example.com' $$, '42501', null, 'Anon cannot update opt-outs');
reset role;
set local role authenticated;
select throws_ok($$ select * from public.email_opt_outs $$, '42501', null, 'Authenticated cannot read opt-outs');
select throws_ok($$ insert into public.email_opt_outs(email) values ('user@example.com') $$, '42501', null, 'Authenticated cannot insert opt-outs');
select throws_ok($$ delete from public.email_opt_outs $$, '42501', null, 'Authenticated cannot delete opt-outs');
select throws_ok($$ update public.email_opt_outs set email = 'user@example.com' $$, '42501', null, 'Authenticated cannot update opt-outs');
reset role;
set local role service_role;
select lives_ok($$ insert into public.email_opt_outs(email) values ('service@example.com') on conflict do nothing $$, 'Service role can stop emails');
select lives_ok($$ insert into public.email_opt_outs(email) values ('service@example.com') on conflict (email) do nothing $$, 'Repeated stop needs no update privilege');
select is((select count(*)::integer from public.email_opt_outs where email = 'service@example.com'), 1, 'Service role can read the suppressed address');
select lives_ok($$ delete from public.email_opt_outs where email = 'service@example.com' $$, 'Service role can resume emails');
select is((select count(*)::integer from public.email_opt_outs where email = 'service@example.com'), 0, 'Resume removes the suppressed address');
reset role;
select * from finish();
rollback;
